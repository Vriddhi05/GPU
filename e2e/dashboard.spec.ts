import { test, expect } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
test('navigation, filters, traceability and screenshots', async ({page})=>{
  await page.setViewportSize({width:1536,height:1024});
  await page.context().grantPermissions(['clipboard-read','clipboard-write']);
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Overview',exact:true})).toBeVisible();
  await expect(page.locator('.recharts-surface').first()).toBeVisible();
  const shots=path.resolve('docs/screenshots');fs.mkdirSync(shots,{recursive:true});
  await page.screenshot({path:path.join(shots,'overview.png'),fullPage:true});
  await page.getByRole('button',{name:'Telemetry'}).click();
  await expect(page.getByRole('heading',{name:'Telemetry Explorer'})).toBeVisible();
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export CSV'}).click();
  expect((await downloadPromise).suggestedFilename()).toBe('gpu-03-telemetry.csv');
  await page.getByLabel('GPU device').selectOption('GPU-01');
  await expect(page.getByText('Source readings for GPU-01')).toBeVisible();
  await page.screenshot({path:path.join(shots,'telemetry.png'),fullPage:true});
  await page.getByRole('button',{name:/Anomalies/}).click();
  await expect(page.getByRole('heading',{name:/Anomaly Events/})).toBeVisible();
  await page.getByLabel('Filter by GPU').selectOption('GPU-02');
  await expect(page.locator('.click-row')).toHaveCount(0);
  await page.getByLabel('Filter by GPU').selectOption('All GPUs');
  await page.locator('.click-row').nth(2).click();
  await expect(page.locator('.json')).toContainText('REC-03-048');
  await page.getByRole('button',{name:'Copy JSON'}).click();
  await expect(page.getByRole('button',{name:'Copied'})).toBeVisible();
  expect(await page.evaluate(()=>navigator.clipboard.readText())).toContain('REC-03-048');
  await page.screenshot({path:path.join(shots,'anomalies.png'),fullPage:true});
  await page.getByRole('button',{name:'Logs'}).click();
  await expect(page.getByRole('heading',{name:'Event Log'})).toBeVisible();
  await page.getByPlaceholder('Search logs…').fill('error count');
  await expect(page.locator('tbody tr')).toHaveCount(2);
  await page.screenshot({path:path.join(shots,'logs.png'),fullPage:true});
});
